//! `README.md` states the corpus B finding total twice, 38 lines apart: once
//! in the benchmark table's "Total findings" row, once as the denominator of
//! the audit-validated precision sentence ("out of `N`"). Nothing re-derived
//! one from the other, so ordinary rule-pack coverage commits landed against
//! the precision paragraph without anyone re-running the benchmark table —
//! `#Y84` found the two had drifted from 1056 to 1853 (a 75.5% gap) after two
//! days and two coverage cycles of silent divergence. `#Y84`'s own fix named
//! this exact check as the right follow-up so the gap can't reopen the same
//! way; this test is that follow-up.
//!
//! Deliberately textual, the same shape `readme_rule_pack_counts.rs` already
//! uses for the rule-pack-count sentences: locate the digits adjacent to
//! fixed anchor text rather than parsing the table or trusting either number
//! to have been kept in sync by hand.

use std::fs;
use std::path::PathBuf;

fn workspace_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .canonicalize()
        .expect("workspace root resolves")
}

/// The run of ASCII digits immediately before `needle` in `haystack`. Panics
/// naming the missing anchor if the sentence has been reworded, so this test
/// fails loudly on a rewrite rather than silently matching nothing.
fn number_before(haystack: &str, needle: &str) -> usize {
    let at = haystack.find(needle).unwrap_or_else(|| {
        panic!(
            "README.md no longer contains {needle:?} — update this test to match the new wording"
        )
    });
    let head = &haystack[..at];
    let digits: String = head
        .chars()
        .rev()
        .take_while(|c| c.is_ascii_digit())
        .collect::<Vec<char>>()
        .into_iter()
        .rev()
        .collect();
    digits
        .parse()
        .unwrap_or_else(|_| panic!("no digits immediately before {needle:?} in README.md"))
}

#[test]
fn readme_benchmark_table_total_matches_the_precision_denominator() {
    let root = workspace_root();
    let readme = fs::read_to_string(root.join("../README.md")).expect("README.md readable");

    // "| Total findings | 1853 |"
    let table_total = number_before(&readme, " |\n| Projects scanned |");
    // "measured 2026-08-31 on 635 audited findings out of 1853, every one labelled"
    let precision_denominator = number_before(&readme, ", every one labelled by opening its cited");

    assert_eq!(
        table_total, precision_denominator,
        "README.md's benchmark table says \"Total findings | {table_total}\", but the \
         audit-validated precision sentence's \"out of {{n}}\" denominator says \
         {precision_denominator} — one was updated without the other. See `#Y84` in \
         03-Product/Backlog.md for why this drift recurs."
    );

    println!("benchmark table and precision denominator agree at {table_total}");
}

/// The run of ASCII digits (and at most one decimal point) immediately before
/// `needle` in `haystack`, kept as a string rather than parsed to a float so
/// the comparison is exact-text rather than numeric-equivalence.
fn token_before(haystack: &str, needle: &str) -> String {
    let at = haystack.find(needle).unwrap_or_else(|| {
        panic!(
            "README.md no longer contains {needle:?} — update this test to match the new wording"
        )
    });
    let head = &haystack[..at];
    head.chars()
        .rev()
        .take_while(|c| c.is_ascii_digit() || *c == '.')
        .collect::<Vec<char>>()
        .into_iter()
        .rev()
        .collect()
}

/// `#Y91`: the same drift shape `#Y84` found in the finding-count total, one
/// section up — the benchmark table is regenerated by a real run, but the
/// lede and the comparison table each keep their own hand-copied restatement
/// of its median/mean/wall-clock figures, and nothing re-derives them from
/// the table. Two of three locations were found stale by one benchmark cycle
/// (205ms/1847ms/277s quoting a superseded run, against the table's own
/// 175ms/1575ms/236.6s) ~31 hours after `#Y84` landed the identical fix for
/// the finding count.
#[test]
fn readme_speed_figures_agree_with_the_benchmark_table() {
    let root = workspace_root();
    let readme = fs::read_to_string(root.join("../README.md")).expect("README.md readable");

    // "| Per project | median 175ms · mean 1575ms · p90 1.19s · max 126.7s |"
    let table_median = token_before(&readme, "ms · mean");
    let table_mean = token_before(&readme, "ms · p90");
    // "| Wall-clock time | 236.6s (3m 57s) for all 150 |"
    let table_wallclock = token_before(&readme, "s (3m");

    // "Median project scans in 175ms; the mean is 1575ms — see the benchmark table"
    let lede_median = token_before(&readme, "ms; the mean");
    let lede_mean = token_before(&readme, "ms — see the benchmark table");

    // "| Scan speed | 175ms median project; 236.6s for the 150-project corpus (2 cores) |"
    let comparison_median = token_before(&readme, "ms median project");
    let comparison_wallclock = token_before(&readme, "s for the 150-project corpus");

    assert_eq!(
        lede_median, table_median,
        "README.md's lede says median {lede_median}ms but the benchmark table says \
         {table_median}ms — the lede is quoting a stale run. See `#Y91` in 03-Product/Backlog.md."
    );
    assert_eq!(
        lede_mean, table_mean,
        "README.md's lede says mean {lede_mean}ms but the benchmark table says {table_mean}ms — \
         the lede is quoting a stale run. See `#Y91` in 03-Product/Backlog.md."
    );
    assert_eq!(
        comparison_median, table_median,
        "README.md's comparison table says median {comparison_median}ms but the benchmark \
         table says {table_median}ms — one was updated without the other. See `#Y91` in \
         03-Product/Backlog.md."
    );
    assert_eq!(
        comparison_wallclock, table_wallclock,
        "README.md's comparison table says {comparison_wallclock}s wall-clock but the \
         benchmark table says {table_wallclock}s — one was updated without the other. See \
         `#Y91` in 03-Product/Backlog.md."
    );

    println!(
        "README speed figures agree: median {table_median}ms, mean {table_mean}ms, wall-clock \
         {table_wallclock}s"
    );
}
